"""Rebuild the paper table from published aggregates; no simulator is required."""
from pathlib import Path
import argparse
import csv
import io

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ('Общая политика, строгий подъём', ['whole_3521']),
    ('Отдельный Approach', ['separate_approach_249']),
    ('Отдельный Grasp, checkpoint 175', ['separate_grasp_175']),
    ('Отдельный Lift, checkpoint 999', ['separate_lift_999']),
    ('Единая, прежний Approach', ['curriculum_v1_approach_10043', 'curriculum_v1_approach_20043']),
    ('Единая, новый Approach', ['curriculum_v2_approach_10043', 'curriculum_v2_approach_20043']),
    ('Единая, новый Grasp', ['curriculum_v2_grasp_10043', 'curriculum_v2_grasp_20043']),
]


def render_outputs():
    with (ROOT / 'results/evaluations.csv').open(encoding='utf-8', newline='') as stream:
        rows = list(csv.DictReader(stream))
    by_id = {row['evaluation_id']: row for row in rows}
    expected = [key for _, keys in GROUPS for key in keys]
    if len(rows) != len(by_id) or set(by_id) != set(expected):
        raise ValueError('Unexpected, missing or duplicated evaluation IDs')
    summary = io.StringIO(newline='')
    writer = csv.writer(summary, lineterminator='\n')
    writer.writerow(['evaluation_id', 'successes', 'episodes', 'success_rate_percent',
                     'stage_transitions', 'total_transitions_known'])
    for row in rows:
        k, n = int(row['successes']), int(row['episodes'])
        if not (n > 0 and 0 <= k <= n):
            raise ValueError(f"Invalid counts: {row['evaluation_id']}")
        stage = row['stage_transitions']
        # Only the new sequential Grasp has a documented preceding stage here.
        total = str(int(stage) + 9_600_000) if row['evaluation_id'].startswith('curriculum_v2_grasp') else stage
        writer.writerow([row['evaluation_id'], k, n, f'{100 * k / n:.3f}', stage, total])
    lines = [
        '% Generated by tools/summarize_results.py; do not edit manually.',
        r'\begin{tabular}{@{}p{0.56\columnwidth}r@{}}',
        r'\toprule',
        r'Модель и оцениваемый этап & Успехи / эпизоды \\',
        r'\midrule',
    ]
    for label, keys in GROUPS:
        counts = '; '.join(f"${by_id[key]['successes']}/{by_id[key]['episodes']}$" for key in keys)
        lines.append(label + ' & ' + counts + r' \\')
    lines.extend([r'\bottomrule', r'\end{tabular}'])
    return {
        ROOT / 'results/table_rows.tex': '\n'.join(lines) + '\n',
        ROOT / 'results/summary.csv': summary.getvalue(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    for path, content in render_outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated file: {path.name}; run tools/summarize_results.py')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    print('PASS: ten evaluations, seven table rows; seeds retained separately')


if __name__ == '__main__':
    main()
